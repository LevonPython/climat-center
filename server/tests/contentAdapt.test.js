const { adaptForArmenia } = require('../scripts/content/adapt');

const text = (input) => adaptForArmenia(input).text;

describe('adaptForArmenia', () => {
  test.each([
    ['Ремонт кондиционеров в Москве', 'Ремонт кондиционеров в Ереване'],
    ['Установка в Москве и Московской области', 'Установка в Ереване'],
    ['Установка в Москве / Московской области:', 'Установка в Ереване:'],
    ['Установка в Москве и области', 'Установка в Ереване'],
    ['Выезд по Москве и МО', 'Выезд по Еревану'],
    ['во всех районах Москвы и Московской области', 'во всех районах Еревана'],
    ['г. Москва', 'г. Ереван'],
    ['Работаем в Подмосковье', 'Работаем в Армении'],
    ['Центр климата в Москве | Ремонт', 'Центр климата в Ереване | Ремонт']
  ])('moves %s to Armenia', (input, expected) => {
    expect(text(input)).toBe(expected);
  });

  test('leaves words that only contain similar letters alone', () => {
    expect(text('Москвич и подмосковная дача')).toBe('Москвич и подмосковная дача');
  });

  test.each([
    ['Чистка кондиционеров от 2000 рублей.', 'Чистка кондиционеров.'],
    ['Диагностика от 500 руб. бесплатно', 'Диагностика бесплатно'],
    ['Обслуживание за 2499 рублей!', 'Обслуживание!'],
    ['Кредитный лимит: от 1500 ₽ до 500 000 ₽', 'Кредитный лимит:'],
    ['Демонтаж 12 000 руб', 'Демонтаж']
  ])('removes the ruble amount from %s', (input, expected) => {
    expect(text(input)).toBe(expected);
  });

  test('keeps numbers that are not prices', () => {
    expect(text('Гарантия 12 месяцев, мощность 7 кВт, скидка 10%')).toBe('Гарантия 12 месяцев, мощность 7 кВт, скидка 10%');
  });

  test('removes what is left of a price per 100 grams', () => {
    expect(text('Заправка кондиционера фреоном/100 г | Дозаправка')).toBe('Заправка кондиционера фреоном | Дозаправка');
    expect(text('<li>R-32 <p>/100 г.</p> <p>Описание</p></li>')).toBe('<li>R-32 <p>Описание</p></li>');
  });

  test.each([
    ['Выбор с учётом данных по СП 131.13330. Далее', 'Выбор с учётом данных. Далее'],
    ['Параметры должны соответствовать СНиП 33-75. Далее', 'Параметры должны соответствовать действующим нормам. Далее'],
    ['соответствует российским и <br /> международным стандартам', 'соответствует национальным и <br /> международным стандартам'],
    ['<h3>Гарантии</h3> Являемся членом СРО. С нами вы', '<h3>Гарантии</h3> С нами вы'],
    [
      'законодательства: Градостроительного кодекса, отраслевых <br /> стандартов и ГОСТов, НД, ТИ, ТУ, архитектурно-строительных <br /> нормативов, требований безопасности, СанПин.',
      'законодательства: градостроительных норм, отраслевых <br /> стандартов, архитектурно-строительных <br /> нормативов, требований безопасности, санитарных норм.'
    ]
  ])('removes the claim that only holds in Russia from %s', (input, expected) => {
    expect(text(input)).toBe(expected);
  });

  test('removes a quote from a named Russian lawyer rather than moving them to Yerevan', () => {
    const input = '<p>Перед</p><blockquote><p>"Ответственность за сосульки несут собственники": юрист, руководитель центра в Москве Иван Иванов.</p></blockquote><p>После</p>';
    const result = adaptForArmenia(input);

    expect(result.text).toBe('<p>Перед</p><p>После</p>');
    expect(result.removed).toHaveLength(1);
  });

  test('removes a promotion with a date', () => {
    expect(text('Чистка кондиционера Скидка 10 % до 15 ноября! Быстро')).toBe('Чистка кондиционера Быстро');
  });

  test('reports what it removed, so it can be listed for review', () => {
    expect(adaptForArmenia('Чистка от 2000 рублей. Скидка 10 % до 15 ноября!').removed).toEqual(['Скидка 10 % до 15 ноября!', 'от 2000 рублей']);
  });

  test('does not touch markup', () => {
    expect(text('<p class="x">Выезд в <a href="/kontakty">Москве</a></p>')).toBe('<p class="x">Выезд в <a href="/kontakty">Москве</a></p>'.replace('Москве', 'Ереване'));
  });
});
